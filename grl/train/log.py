def _jsonable(v):
    if isinstance(v, dict):
        return {str(k): _jsonable(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [_jsonable(x) for x in v]
    if isinstance(v, (np.floating, np.integer)):
        return v.item()
    if isinstance(v, torch.Tensor):
        return v.item() if v.numel() == 1 else v.tolist()
    return v


class RunLogger:
    def __init__(self, run_dir, manifest: dict | None = None, resume: bool = False):
        self.dir = Path(run_dir)
        if self.dir.exists() and any(self.dir.iterdir()) and not resume:
            raise FileExistsError(f"{self.dir} exists and is not empty: pass --resume or choose a new run dir")
        self.dir.mkdir(parents=True, exist_ok=True)
        if manifest is not None and not resume:
            (self.dir / "manifest.json").write_text(json.dumps(_jsonable(manifest), ensure_ascii=False, indent=1,
                                                               sort_keys=True) + "\n", encoding="utf-8")
        if resume and (self.dir / "metrics.jsonl").exists():
            self._rewrite(read_rows(self.dir))                # drops a torn tail so it never becomes a middle line
        self._f = (self.dir / "metrics.jsonl").open("a", encoding="utf-8")

    def _rewrite(self, rows: list[dict]) -> None:
        f = self.dir / "metrics.jsonl"
        tmp = f.with_name(f.name + ".tmp")
        tmp.write_text("".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in rows),
                       encoding="utf-8")
        os.replace(tmp, f)

    def log(self, phase: str, step: int, **m) -> dict:
        row = {"phase": phase, "step": int(step), "time": round(time.time(), 3), **_jsonable(m)}
        self._f.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
        self._f.flush()
        return row

    def truncate(self, max_step: dict) -> None:
        """Resume: drop rows of `phase` with step > max_step[phase] (they are recomputed)."""
        self._f.close()
        keep = [r for r in read_rows(self.dir) if not (r["phase"] in max_step and r["step"] > max_step[r["phase"]])]
        self._rewrite(keep)
        for c in self.dir.glob("*.csv"):                      # stale exports: regenerated by export_csv()
            c.unlink()
        self._f = (self.dir / "metrics.jsonl").open("a", encoding="utf-8")

    def export_csv(self) -> list[Path]:
        rows, out = read_rows(self.dir), []
        for c in self.dir.glob("*.csv"):
            if c.stem not in {r["phase"] for r in rows}:
                c.unlink()
        for phase in sorted({r["phase"] for r in rows}):
            flat = [_flat(r) for r in rows if r["phase"] == phase]
            cols = sorted({k for r in flat for k in r})
            f = self.dir / f"{phase}.csv"
            with f.open("w", newline="", encoding="utf-8") as fh:
                wr = csv.DictWriter(fh, fieldnames=cols)
                wr.writeheader()
                wr.writerows(flat)
            out.append(f)
        return out

    def close(self) -> None:
        self._f.close()


def _flat(r: dict, prefix: str = "") -> dict:
    out = {}
    for k, v in r.items():
        if isinstance(v, dict):
            out.update(_flat(v, f"{prefix}{k}."))
        elif isinstance(v, (int, float, str, bool)) or v is None:
            out[f"{prefix}{k}"] = v
        else:
            out[f"{prefix}{k}"] = json.dumps(v, ensure_ascii=False)
    return out


def read_rows(run_dir) -> list[dict]:
    """A torn final line (kill mid-write) is skipped; an unparsable line anywhere else raises."""
    f = Path(run_dir) / "metrics.jsonl"
    if not f.exists():
        return []
    lines = [l for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]
    rows = []
    for i, l in enumerate(lines):
        try:
            rows.append(json.loads(l))
        except json.JSONDecodeError:
            if i != len(lines) - 1:
                raise
    return rows


def comparable(rows: list[dict]) -> list[dict]:
    """Rows without the wall-clock `time` field, for run-vs-run equality checks (resume, Tasks 10/12)."""
    return [{k: v for k, v in r.items() if k != "time"} for r in rows]


def alarms(m: dict, cfg: dict) -> list[str]:
    out = []
    if m.get("tmax_share", 0.0) > cfg["tmax_share"]:
        out.append(f"t_max: {m['tmax_share']:.2f} of episodes hit T_max -- the stop rule is not learnt (§8.7)")
    ops = {k: v for k, v in (m.get("op_hist") or {}).items() if k != "stop"}
    tot = sum(ops.values())
    if tot and max(ops.values()) / tot > cfg["op_collapse_share"]:
        top = max(ops, key=ops.get)
        out.append(f"collapse: {top} takes {ops[top] / tot:.2f} of the non-STOP actions (§8.7)")
    fp = cfg.get("first_pick_collapse")                       # pilot 6 rank (grl.train.rank.rank_alarm_cfg)
    if fp is not None and m.get("first_slot0_share") is not None and m["first_slot0_share"] > fp:
        out.append(f"collapse: the fused top candidate is ranked first in {m['first_slot0_share']:.2f} of the "
                   f"episodes (> {fp:.2f}, §8.7 rank)")
    if m.get("kl_ref", 0.0) > cfg["kl_max"]:
        out.append(f"kl: KL(π‖π_ref) {m['kl_ref']:.3f} > {cfg['kl_max']} -- the policy drifted (§8.6)")
    if "stop_share" in m and m["stop_share"] < cfg["stop_share_min"]:
        out.append(f"stop: only {m['stop_share']:.2f} of episodes end with STOP (§8.6)")
    return out


def expert_slot0_share(items) -> float:
    """Rerank: share of slot 0 (action 1, the fused top candidate) among the expert's selections on the given items."""
    sel = [int(a) for it in items for a in it.actions if int(a) != 0]
    return sum(1 for a in sel if a == 1) / len(sel) if sel else 0.0


def slot_top_share(op_hist) -> float | None:
    """Rerank: share of the most used candidate slot among the selections of op_hist (None without selections)."""
    sel = {k: v for k, v in (op_hist or {}).items() if str(k).startswith("select:")}
    tot = sum(sel.values())
    return max(sel.values()) / tot if tot else None


def rerank_alarm_cfg(cfg: dict, slot0_share: float, margin: float = 0.05) -> dict:
    """Rerank §8.7 collapse: one slot dominating is expected when the expert itself mostly takes slot 0, so the alarm
    fires only above max(op_collapse_share, expert slot-0 share on train + margin)."""
    return {**cfg, "op_collapse_share": max(float(cfg["op_collapse_share"]), float(slot0_share) + margin),
            "expert_slot0_share": round(float(slot0_share), 6)}


def hacking_alarm(train_means, val_means) -> bool:
    """§8.7 "награда растёт, качество нет": over the last three validations train reward rises, val reward falls."""
    t, v = list(train_means)[-3:], list(val_means)[-3:]
    return len(t) == 3 == len(v) and t[0] < t[1] < t[2] and v[0] > v[1] > v[2]


PANELS = [("sft", "loss", "SFT: loss"), ("sft_val", "val_reward_mean", "SFT: val reward"),
          ("grpo", "reward_mean", "GRPO: mean reward"), ("grpo", "reward_group_std", "GRPO: within-group std"),
          ("grpo", "kl_ref", "GRPO: KL to π_ref"), ("grpo", "stop_share", "GRPO: STOP share"),
          ("grpo", "ep_len_mean", "GRPO: episode length"), ("grpo_val", "val_reward_mean", "GRPO: val reward")]


def plot_run(run_dir) -> list[Path]:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return []
    rows, out, files = read_rows(run_dir), Path(run_dir) / "plots", []
    out.mkdir(exist_ok=True)
    for phase, key, title in PANELS:
        pts = [(r["step"], r[key]) for r in rows if r["phase"] == phase and isinstance(r.get(key), (int, float))]
        if not pts:
            continue
        fig, ax = plt.subplots(figsize=(6, 3.2))
        ax.plot([p[0] for p in pts], [p[1] for p in pts], linewidth=1.5, color="#3b6ea5")
        ax.set_title(title)
        ax.set_xlabel("step")
        ax.grid(alpha=0.3)
        fig.tight_layout()
        f = out / f"{phase}_{key}.png"
        fig.savefig(f, dpi=120)
        plt.close(fig)
        files.append(f)
    ops = {}
    for r in rows:
        if r["phase"] == "grpo":
            for k, v in (r.get("op_hist") or {}).items():
                ops[k] = ops.get(k, 0) + v
    if ops:
        fig, ax = plt.subplots(figsize=(6, 3.2))
        names = sorted(ops)
        ax.barh(names, [ops[n] for n in names], color="#3b6ea5")
        ax.set_title("GRPO: operators, all iterations")
        fig.tight_layout()
        f = out / "grpo_op_hist.png"
        fig.savefig(f, dpi=120)
        plt.close(fig)
        files.append(f)
    return files


def _atomic_save(state, p: Path) -> None:
    """A kill mid-save must not leave a torn last.pt that --resume then trips over."""
    tmp = p.with_name(p.name + ".tmp")
    torch.save(state, tmp)
    os.replace(tmp, p)


class Checkpoints:
    def __init__(self, d, keep_top: int = 3):
        self.d, self.keep = Path(d), int(keep_top)
        self.d.mkdir(parents=True, exist_ok=True)
        f = self.d / "index.json"
        self.index = json.loads(f.read_text(encoding="utf-8")) if f.exists() else {"top": [], "last": None}
        known = {r["name"] for r in self.index["top"]} | {"last"}
        for p in self.d.glob("*.pt"):                         # orphans of a kill between .pt and index writes
            if p.stem not in known:
                p.unlink()
        for p in self.d.glob("*.tmp"):
            p.unlink()

    def _write_index(self) -> None:
        f = self.d / "index.json"
        tmp = f.with_name(f.name + ".tmp")
        tmp.write_text(json.dumps(self.index, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        os.replace(tmp, f)

    def save(self, name: str, state: dict, metric: float | None) -> Path:
        if name == "last":
            raise ValueError('checkpoint name "last" is reserved')
        p = self.d / f"{name}.pt"
        _atomic_save(state, self.d / "last.pt")
        self.index["last"] = name
        evict = []
        if metric is not None:
            _atomic_save(state, p)
            top = sorted([r for r in self.index["top"] if r["name"] != name] +
                         [{"name": name, "metric": float(metric)}], key=lambda r: (-r["metric"], r["name"]))
            evict, self.index["top"] = top[self.keep:], top[:self.keep]
        self._write_index()                                   # index first, then delete: a kill leaves only orphans
        for r in evict:
            (self.d / f"{r['name']}.pt").unlink(missing_ok=True)
        return p

    def last_path(self) -> Path:
        return self.d / "last.pt"

    def has_best(self) -> bool:
        return bool(self.index["top"])

    def best(self) -> Path:
        if not self.index["top"]:
            raise FileNotFoundError(f"no scored checkpoint in {self.d}")
        return self.d / f"{self.index['top'][0]['name']}.pt"


def _git(*args) -> str | None:
    try:
        r = subprocess.run(["git", *args], cwd=config.ROOT, capture_output=True, text=True, timeout=10)
        return r.stdout.strip() if r.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def run_manifest(cfg: dict, inputs: dict, extra: dict | None = None) -> dict:
    import torch_geometric
    head = _git("rev-parse", "HEAD")
    src = config.path("data/m5/SOURCE_GIT_HEAD")                  # written by scripts/spark.py sync (no .git there)
    return {"git_head": head or (src.read_text().strip() if src.exists() else None),
            "git_dirty": bool(_git("status", "--porcelain", "--", ".")) if head else None,
            "graph_version": cfg["env"]["graph_version"],
            "config_sha256": hashlib.sha256(json.dumps(cfg, sort_keys=True, ensure_ascii=False).encode()).hexdigest(),
            "inputs": {k: sha256_file(v) for k, v in inputs.items() if v and Path(v).is_file()},
            "versions": {"python": platform.python_version(), "torch": torch.__version__,
                         "torch_geometric": torch_geometric.__version__, "numpy": np.__version__,
                         "cuda": torch.version.cuda},
            "machine": platform.machine(), "node": platform.node(), **(extra or {})}


def set_determinism(seed: int, mode: str = "strict") -> dict:
    if mode not in ("strict", "warn", "off"):
        raise ValueError(f"run.deterministic {mode!r} is not strict | warn | off")
    os.environ.setdefault("CUBLAS_WORKSPACE_CONFIG", ":4096:8")
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.benchmark = False
    torch.use_deterministic_algorithms(mode != "off", warn_only=mode == "warn")
    return {"seed": int(seed), "mode": mode}


def pick_device(name: str = "auto") -> torch.device:
    if name != "auto":
        return torch.device(name)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")
